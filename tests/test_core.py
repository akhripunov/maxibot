from app.domain.services import channel_card_text, menu_text

def test_main_menu_contains_counters():
    text = menu_text(2, 1, 7)
    assert text == (
        "🤖  MAXIBOT\n\n"
        "Всё для управления и продвижения каналов MAX:\n\n"
        "📣  Продвижение - Создавайте лендинг для канала, запускайте рекламу\n"
        "в Яндекс Директе и отслеживайте подписки.\n\n"
        "📩  Обращения / Предложка - Подключайте каналы и получайте обращения подписчиков в отдельные рабочие чаты.\n\n"
        "🤖  Мои боты - Подключайте собственных ботов, чтобы подписчики писали и получали ответы от имени вашего бренда.\n\n"
        "📚 Каналов подключено: 2\n"
        "🤖 Собственных ботов: 7"
    )

def test_channel_card_reflects_disabled_state():
    text = channel_card_text("Петербург 24", False, 1, 3, "2026-08-05 12:00", "abc")
    assert "⛔ Статус: не принимает сообщения" in text
    assert "✅ Включить приём сообщений" not in text
